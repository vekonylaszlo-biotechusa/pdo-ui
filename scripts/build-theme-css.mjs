// Generates dist/theme.css from src/styles.css: the raw, UNPROCESSED design
// tokens (CSS custom properties + the Tailwind v4 `@theme inline`
// registration), with none of it run through postcss/Tailwind.
//
// Why this exists: dist/styles.css (built by `rslib build`) is the fully
// compiled, closed output — Tailwind already consumed the `@theme inline`
// block there and only kept the specific utility classes pdo-ui's own
// components use. A consumer app that runs its OWN Tailwind build and wants
// to `@apply bg-background` (or any other utility derived from these same
// tokens) in its own CSS needs the `@theme` registration as literal source,
// not pre-compiled output, so its Tailwind engine can generate that utility
// itself. dist/theme.css is that raw source.
//
// Run via `npm run build` (chained after `rslib build`) — see package.json.
//
// Consumers: import this BEFORE any of your own `@apply` usages, right
// after `@import "tailwindcss";`, e.g.:
//   @import "tailwindcss";
//   @import "@biotechusa/pdo-ui/dist/theme.css";
//   @import "@biotechusa/pdo-ui/dist/styles.css";  <- unchanged, still needed
//   :root { @apply bg-background; }                <- now resolves

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "src/styles.css");
const OUT = path.join(ROOT, "dist/theme.css");

const text = fs.readFileSync(SRC, "utf-8");

function findBlock(text, startPat) {
  const m = startPat.exec(text);
  if (!m) {
    throw new Error(`build-theme-css: pattern not found in src/styles.css: ${startPat}`);
  }
  let i = m.index + m[0].length; // just after the opening '{'
  let depth = 1;
  while (depth > 0) {
    if (i >= text.length) {
      throw new Error(`build-theme-css: unbalanced braces while scanning block: ${startPat}`);
    }
    const c = text[i];
    if (c === "{") depth++;
    else if (c === "}") depth--;
    i++;
  }
  return { start: m.index, end: i };
}

const blockPatterns = [
  [':root', /^:root \{/m],
  ['[data-theme="dark"]', /^\[data-theme="dark"\] \{/m],
  ['[data-theme="oblivion"]', /^\[data-theme="oblivion"\] \{/m],
  ['[data-theme="rsi"]', /^\[data-theme="rsi"\] \{/m],
  ['@theme inline', /^@theme inline \{/m],
];

const pieces = blockPatterns.map(([, pat]) => {
  const { start, end } = findBlock(text, pat);
  return text.slice(start, end).trimEnd();
});

const header = `/* AUTO-GENERATED by scripts/build-theme-css.mjs from src/styles.css. DO NOT EDIT DIRECTLY.
 * Raw, unprocessed design tokens (CSS custom properties + the Tailwind v4
 * @theme registration) for consumers running their own Tailwind build who
 * want utilities like bg-background / bg-muted generated from these same
 * tokens. Import this before your own @apply usages. Import
 * dist/styles.css separately (unchanged) for pdo-ui's own compiled
 * component styles.
 */

`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, header + pieces.join("\n\n") + "\n");

console.log(`build-theme-css: wrote ${path.relative(ROOT, OUT)} (${fs.statSync(OUT).size} bytes)`);
